import { defineRouteMiddleware } from "@astrojs/starlight/route-data";
import type { StarlightRouteData } from "@astrojs/starlight/route-data";
import config from "virtual:starlight/user-config";
// Starlight exports none of these helpers from its package entry points, so
// they are imported by path, as src/pages/[file].txt.ts does; if a Starlight
// upgrade moves them, the build fails here.
import {
  getPrevNextLinks,
  getSidebar,
  getSidebarFromConfig,
} from "../node_modules/@astrojs/starlight/utils/navigation.ts";
import { getLocaleRoutes } from "../node_modules/@astrojs/starlight/utils/routing/index.ts";
import { slugToPathname } from "../node_modules/@astrojs/starlight/utils/slugs.ts";
import { formatPath } from "../node_modules/@astrojs/starlight/utils/format-path.ts";
import untranslatedPages from "virtual:aggrega-docs/untranslated-pages";
import { sourceRouteOf } from "./translations.mjs";
import { localizeSidebarConfig } from "./sidebar-labels.mjs";

// The route data of a page in a published language.
//
// A translated page that still holds English text, because the translation
// memory has no translation for some of its text, is marked as not fully
// translated, so Starlight shows its notice, in the page's language, above it.
//
// The sidebar of a translated page is the English sidebar with every link to a
// page of the site pointing at that page in the same language, under the
// page's title in that language, and with every label the sidebar's
// configuration gives, of a group, a link or a badge, in that language.
// Starlight builds an autogenerated sidebar group from the pages' file paths,
// and the translated pages sit in their own tree outside its content
// directory, so it cannot place them itself; mapping the English sidebar keeps
// one sidebar, in one order, for every language. The configured labels come
// from a second sidebar, which Starlight builds once per language from the
// configuration with its labels in that language (src/sidebar-labels.mjs) and
// from the English pages. Built from configurations of one shape over the same
// pages, the two sidebars hold the same entries in the same places, so each
// label is taken from the entry in the same place; a label is never matched by
// its English text, which two different groups may share. The previous and
// next links follow the mapped sidebar.

type Entry = StarlightRouteData["sidebar"][number];
type Localized = { href: string; title: string };

const untranslated = new Set<string>(untranslatedPages);

const englishTitles = new Map<string, string>(
  getLocaleRoutes(undefined).map((route) => [hrefOf(route.id), String(route.entry.data.title)]),
);
const byLocale = new Map<string, Map<string, Localized>>();
const labelledByLocale = new Map<string, Entry[]>();

function hrefOf(id: string): string {
  return formatPath(slugToPathname(id));
}

// For one language: each English page's address, to that page's address and
// title in the language.
function localizedPages(locale: string): Map<string, Localized> {
  let pages = byLocale.get(locale);
  if (!pages) {
    pages = new Map(
      getLocaleRoutes(locale).map((route) => [
        hrefOf(sourceRouteOf(route.id, locale)),
        { href: hrefOf(route.id), title: String(route.entry.data.title) },
      ]),
    );
    byLocale.set(locale, pages);
  }
  return pages;
}

// For one language: the sidebar Starlight builds from the configuration with
// its labels in that language, over the English pages, whose entries stand in
// the places of the English sidebar's.
function labelledSidebar(locale: string, lang: string): Entry[] {
  let sidebar = labelledByLocale.get(locale);
  if (!sidebar) {
    sidebar = getSidebarFromConfig(localizeSidebarConfig(config.sidebar, lang), "", undefined);
    labelledByLocale.set(locale, sidebar);
  }
  return sidebar;
}

function described(entry: Entry | undefined): string {
  if (!entry) return "no entry";
  return entry.type === "group" ? `the group "${entry.label}"` : `the link "${entry.label}" to ${entry.href}`;
}

// The English sidebar's entries in one language: a group takes its label and
// badge, and a link its badge and its configured label, from the entry in the
// same place in `labelled`, the sidebar built with the language's labels. A link
// to a page of the site points at the page in the language, and a link the
// sidebar names by its page's English title, with no translation of its own, is
// named by the page's title in the language.
function localize(entries: Entry[], labelled: Entry[], pages: Map<string, Localized>, locale: string): Entry[] {
  const mismatch = (index: number) =>
    new Error(
      `The sidebar built with the labels of ${locale} holds ${described(labelled[index])} where the ` +
        `English sidebar holds ${described(entries[index])}; both are built from the sidebar ` +
        "configuration over the English pages, so each entry must stand in the same place in both.",
    );
  if (labelled.length > entries.length) throw mismatch(entries.length);
  return entries.map((entry, index) => {
    const counterpart = labelled[index];
    if (entry.type === "group") {
      if (counterpart?.type !== "group") throw mismatch(index);
      return {
        ...entry,
        label: counterpart.label,
        badge: counterpart.badge,
        entries: localize(entry.entries, counterpart.entries, pages, locale),
      };
    }
    if (counterpart?.type !== "link" || counterpart.href !== entry.href) throw mismatch(index);
    const page = pages.get(entry.href);
    const translated = counterpart.label !== entry.label;
    const namedByTitle = page !== undefined && entry.label === englishTitles.get(entry.href);
    const label = page && namedByTitle && !translated ? page.title : counterpart.label;
    return { ...entry, href: page ? page.href : entry.href, label, badge: counterpart.badge };
  });
}

// Every top-level group of the sidebar is rendered collapsed except the one
// holding the page, and "Start here", the first group, on a page no group
// holds. A group nested in another keeps its configured state. The groups a
// reader opens stay open on the next pages of the visit through the script in
// src/components/Sidebar.astro; without it the page still shows its own group
// open.
function collapseTopLevel(entries: Entry[]): Entry[] {
  const holdsPage = (entry: Entry): boolean =>
    entry.type === "group" ? entry.entries.some(holdsPage) : entry.isCurrent;
  const here = Math.max(
    0,
    entries.findIndex((entry) => entry.type === "group" && holdsPage(entry)),
  );
  return entries.map((entry, index) =>
    entry.type === "group" ? { ...entry, collapsed: index !== here } : entry,
  );
}

export const onRequest = defineRouteMiddleware((context) => {
  const route = context.locals.starlightRoute;
  const { locale, lang } = route;
  if (locale) {
    if (untranslated.has(route.id)) route.isFallback = true;
    const english = getSidebar(hrefOf(sourceRouteOf(route.id, locale)), undefined);
    route.sidebar = localize(english, labelledSidebar(locale, lang), localizedPages(locale), locale);
    route.pagination = getPrevNextLinks(route.sidebar, config.pagination, route.entry.data);
  }
  route.sidebar = collapseTopLevel(route.sidebar);
});
