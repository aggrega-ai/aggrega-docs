import { defineRouteMiddleware } from "@astrojs/starlight/route-data";
import type { StarlightRouteData } from "@astrojs/starlight/route-data";
import config from "virtual:starlight/user-config";
// Starlight exports none of these helpers from its package entry points, so
// they are imported by path, as src/pages/[file].txt.ts does; if a Starlight
// upgrade moves them, the build fails here.
import { getPrevNextLinks, getSidebar } from "../node_modules/@astrojs/starlight/utils/navigation.ts";
import { getLocaleRoutes } from "../node_modules/@astrojs/starlight/utils/routing/index.ts";
import { slugToPathname } from "../node_modules/@astrojs/starlight/utils/slugs.ts";
import { formatPath } from "../node_modules/@astrojs/starlight/utils/format-path.ts";
import untranslatedPages from "virtual:aggrega-docs/untranslated-pages";
import { sourceRouteOf } from "./translations.mjs";

// The route data of a page in a published language.
//
// A translated page that still holds English text, because the translation
// memory has no translation for some of its text, is marked as not fully
// translated, so Starlight shows its notice, in the page's language, above it.
//
// The sidebar of a translated page is the English sidebar with every link to a
// page of the site pointing at that page in the same language, under the
// page's title in that language. Starlight builds an autogenerated sidebar
// group from the pages' file paths, and the translated pages sit in their own
// tree outside its content directory, so it cannot place them itself; mapping
// the English sidebar keeps one sidebar, in one order, for every language. The
// previous and next links follow the mapped sidebar.

type Entry = StarlightRouteData["sidebar"][number];
type Localized = { href: string; title: string };

const untranslated = new Set<string>(untranslatedPages);

const englishTitles = new Map<string, string>(
  getLocaleRoutes(undefined).map((route) => [hrefOf(route.id), String(route.entry.data.title)]),
);
const byLocale = new Map<string, Map<string, Localized>>();

function hrefOf(id: string): string {
  return formatPath(slugToPathname(id));
}

// For one language: each English page's address, to that page's address and
// title in the language.
function localizedPages(locale: string): Map<string, Localized> {
  let pages = byLocale.get(locale);
  if (!pages) {
    pages = new Map(
      getLocaleRoutes(locale).map((route) => [
        hrefOf(sourceRouteOf(route.id, locale)),
        { href: hrefOf(route.id), title: String(route.entry.data.title) },
      ]),
    );
    byLocale.set(locale, pages);
  }
  return pages;
}

function localize(entries: Entry[], pages: Map<string, Localized>): Entry[] {
  return entries.map((entry) => {
    if (entry.type === "group") return { ...entry, entries: localize(entry.entries, pages) };
    const page = pages.get(entry.href);
    if (!page) return { ...entry };
    // A label set in the sidebar configuration stays; a page's own title is
    // replaced by its title in the language.
    const label = entry.label === englishTitles.get(entry.href) ? page.title : entry.label;
    return { ...entry, href: page.href, label };
  });
}

// Every top-level group of the sidebar is rendered collapsed except the one
// holding the page, and "Start here", the first group, on a page no group
// holds. A group nested in another keeps its configured state. The groups a
// reader opens stay open on the next pages of the visit through the script in
// src/components/Sidebar.astro; without it the page still shows its own group
// open.
function collapseTopLevel(entries: Entry[]): Entry[] {
  const holdsPage = (entry: Entry): boolean =>
    entry.type === "group" ? entry.entries.some(holdsPage) : entry.isCurrent;
  const here = Math.max(
    0,
    entries.findIndex((entry) => entry.type === "group" && holdsPage(entry)),
  );
  return entries.map((entry, index) =>
    entry.type === "group" ? { ...entry, collapsed: index !== here } : entry,
  );
}

export const onRequest = defineRouteMiddleware((context) => {
  const route = context.locals.starlightRoute;
  const { locale } = route;
  if (locale) {
    if (untranslated.has(route.id)) route.isFallback = true;
    const english = getSidebar(hrefOf(sourceRouteOf(route.id, locale)), undefined);
    route.sidebar = localize(english, localizedPages(locale));
    route.pagination = getPrevNextLinks(route.sidebar, config.pagination, route.entry.data);
  }
  route.sidebar = collapseTopLevel(route.sidebar);
});
