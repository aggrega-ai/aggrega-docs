// The site is served under the /docs subdirectory of the main domain. Content
// is single-sourced from the repository's Markdown corpus via the docs
// collection defined in src/content.config.ts. The sidebar order and labels are
// supplied here; each page's visible title comes from its first heading.
//
// A single source tree is built once per documentation version. The latest
// version is served at /docs; every other version is served under a
// version-prefixed base such as /docs/v0.1. The base and the latest flag are
// derived from the environment (see src/versioning.mjs); with no environment
// set this is the default /docs build.
const { base } = resolveVersioning();

// Starlight's autogenerated sidebar groups select pages by each page's file
// path relative to this project, with its default content directory stripped.
// The corpus is read from outside that directory, so those paths start at the
// corpus root as seen from here ("../authoring/…"), and an autogenerate
// directory has to be written the same way to match any page.
const corpusFromProject = path
  .relative(fileURLToPath(new URL(".", import.meta.url)), corpusRoot)
  .split(path.sep)
  .join("/");
const corpusDirectory = (directory) => `${corpusFromProject}/${directory}`;

// English is the root locale, served unprefixed at /docs; every published
// language is served under its own path segment (src/translations.mjs reads the
// list). A translated heading carries its English heading's identifier, which
// the translation package's plugin turns into the heading's id, so an anchor
// link resolves in every language. The plugin is needed only where translated
// pages are present; without them, every page of a published language is the
// English page with Starlight's notice that it is not translated.
const remarkHeadingIds = hasTranslatedTrees()
  ? [(await translationPackage()).remarkHeadingIds]
  : [];

